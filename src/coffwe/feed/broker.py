"""The local Mosquitto broker: config, credentials, start/stop.

The broker is a project-owned process, not a global background service:

    uv run python -m coffwe.feed broker setup   # passwords into .env + password file
    uv run python -m coffwe.feed broker start   # runs in the foreground (Ctrl-C stops)

Config, password file, persistence and logs live in data/mosquitto/ (gitignored). The
ACL is committed (infra/mosquitto/acl). It listens on localhost only and refuses
anonymous clients -- even locally, it's worth practising the real setup.
"""

import os
import secrets
import shutil
import socket
import subprocess
import time
from dataclasses import dataclass
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[3]
ACL_FILE = ROOT / "infra" / "mosquitto" / "acl"
DATA_DIR = ROOT / "data" / "mosquitto"
ENV_FILE = ROOT / ".env"
ROLES = ("devices", "ingest", "admin")
DEFAULT_PORT = 1883


def mosquitto_bin(name: str = "mosquitto") -> str:
    for candidate in (
        shutil.which(name),
        f"/opt/homebrew/opt/mosquitto/sbin/{name}",
        f"/opt/homebrew/opt/mosquitto/bin/{name}",
    ):
        if candidate and Path(candidate).exists():
            return candidate
    raise FileNotFoundError(f"{name} not found -- brew install mosquitto")


@dataclass(frozen=True)
class BrokerSettings:
    host: str
    port: int
    passwords: dict[str, str]

    def credentials(self, role: str) -> tuple[str, str]:
        return role, self.passwords[role]


def settings() -> BrokerSettings:
    load_dotenv(ENV_FILE)
    return BrokerSettings(
        host=os.environ.get("MQTT_HOST", "127.0.0.1"),
        port=int(os.environ.get("MQTT_PORT", DEFAULT_PORT)),
        passwords={r: os.environ.get(f"MQTT_{r.upper()}_PASSWORD", "") for r in ROLES},
    )


def write_config(directory: Path, port: int, passwords: dict[str, str]) -> Path:
    """Render mosquitto.conf + password file into `directory`; returns the conf path."""
    directory.mkdir(parents=True, exist_ok=True)
    pwfile = directory / "passwd"
    pwfile.write_text("")
    pwfile.chmod(0o600)  # mosquitto refuses world-readable password files
    for role, password in passwords.items():
        subprocess.run(
            [mosquitto_bin("mosquitto_passwd"), "-b", str(pwfile), role, password],
            check=True,
            capture_output=True,
        )
    conf = directory / "mosquitto.conf"
    conf.write_text(
        f"""# Generated by coffwe.feed.broker -- edit infra/mosquitto/acl, not this file.
listener {port} 127.0.0.1
allow_anonymous false
password_file {pwfile}
acl_file {ACL_FILE}
persistence true
persistence_location {directory}/
log_dest file {directory}/mosquitto.log
log_type error
log_type warning
log_type notice
"""
    )
    return conf


def setup() -> BrokerSettings:
    """Create passwords (once, into .env) and the broker's config in data/mosquitto/."""
    load_dotenv(ENV_FILE)
    lines = ENV_FILE.read_text().splitlines() if ENV_FILE.exists() else []
    added = []
    for role in ROLES:
        key = f"MQTT_{role.upper()}_PASSWORD"
        if not os.environ.get(key):
            value = secrets.token_urlsafe(18)
            lines.append(f"{key}={value}")
            os.environ[key] = value
            added.append(key)
    for key, default in (("MQTT_HOST", "127.0.0.1"), ("MQTT_PORT", str(DEFAULT_PORT))):
        if not os.environ.get(key):
            lines.append(f"{key}={default}")
            os.environ[key] = default
    if added or not ENV_FILE.exists():
        ENV_FILE.write_text("\n".join(lines) + "\n")
    s = settings()
    write_config(DATA_DIR, s.port, s.passwords)
    return s


def wait_for_port(host: str, port: int, timeout: float = 5.0) -> None:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        with socket.socket() as sock:
            if sock.connect_ex((host, port)) == 0:
                return
        time.sleep(0.05)
    raise TimeoutError(f"broker didn't open {host}:{port}")


def start(conf: Path, host: str = "127.0.0.1", port: int = DEFAULT_PORT) -> subprocess.Popen:
    """Start mosquitto in the background and wait until it accepts connections."""
    proc = subprocess.Popen(
        [mosquitto_bin(), "-c", str(conf)], stdout=subprocess.DEVNULL, stderr=subprocess.PIPE
    )
    try:
        wait_for_port(host, port)
    except TimeoutError as err:
        proc.terminate()
        detail = proc.stderr.read().decode() if proc.stderr else "broker failed"
        raise RuntimeError(detail) from err
    return proc


def free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]
